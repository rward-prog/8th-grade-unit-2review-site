#!/usr/bin/env python3
"""Build one unit's single-file site.   Usage:  python3 build.py units/8-forces
Output: dist/<grade>/<unit>/index.html
Keeps units/<unit>/registry.lock.json (APPEND-ONLY list of every question/skill ID, in save-code slot order)."""
import json, os, subprocess, sys, re
ROOT = os.path.dirname(os.path.abspath(__file__))

def unit_parts(unit_dir):
    """Ordered list of source files for a unit. Shared by build.py and tests (tests/load.js mirrors this order)."""
    u = os.path.join(ROOT, unit_dir)
    unit_js = sorted(f for f in os.listdir(u) if f.endswith('.js') and not f.startswith('registry'))
    meta = [f for f in unit_js if f.startswith('00-')]
    banks = [f for f in unit_js if re.match(r'1\d-bank', f)]
    content = [f for f in unit_js if f.startswith('20-')]
    return meta, banks, content

def unit_meta_text(unit_dir):
    t = open(os.path.join(ROOT, unit_dir, '00-unit.js')).read()
    g = re.search(r"grade:\s*(\d+)", t).group(1); i = re.search(r"id:\s*'([^']+)'", t).group(1)
    return g, i

def main():
    unit_dir = sys.argv[1] if len(sys.argv) > 1 else 'units/8-forces'
    u = os.path.join(ROOT, unit_dir)
    grade, uid = unit_meta_text(unit_dir)
    keys = json.loads(subprocess.check_output(['node', os.path.join(ROOT, 'tests', 'keys.js')], cwd=ROOT, env=dict(os.environ, UNIT_DIR=unit_dir)))
    lock_path = os.path.join(u, 'registry.lock.json')
    lock = json.load(open(lock_path)) if os.path.exists(lock_path) else []
    missing = [k for k in lock if k not in keys]
    if missing:
        sys.exit('BUILD STOPPED: these IDs are in registry.lock.json but missing from the bank (IDs are permanent): %s' % missing)
    registry = lock + [k for k in keys if k not in lock]
    if len(registry) > 255:
        sys.exit('BUILD STOPPED: more than 255 IDs. Add save-code version 2 before growing the registry further.')
    json.dump(registry, open(lock_path, 'w'), indent=1)
    reg_js = os.path.join(u, 'registry.generated.js')
    open(reg_js, 'w').write("'use strict';\n/* GENERATED by build.py from registry.lock.json. Append-only. Do not edit. */\nconst REGISTRY = %s;\n" % json.dumps(registry))
    meta, banks, content = unit_parts(unit_dir)
    order = [os.path.join(ROOT, 'rosters', 'grade%s.js' % grade), os.path.join(ROOT, 'engine', '01-core.js'), os.path.join(ROOT, 'engine', '05-murphy.js')]
    order += [os.path.join(u, f) for f in meta] + [os.path.join(ROOT, 'engine', '02-qapi.js')]
    order += [os.path.join(u, f) for f in banks + content] + [reg_js]
    order += [os.path.join(ROOT, 'engine', f) for f in ('40-engine.js', '50-codes.js', '90-ui.js')]
    js = '\n'.join('/* ---- %s ---- */\n%s' % (os.path.relpath(f, ROOT), open(f).read()) for f in order)
    css = open(os.path.join(ROOT, 'engine', 'style.css')).read()
    html = open(os.path.join(ROOT, 'engine', 'template.html')).read()
    title = re.search(r"title:\s*'([^']+)'", open(os.path.join(u, '00-unit.js')).read()).group(1)
    html = html.replace('/*__CSS__*/', css).replace('/*__JS__*/', js.replace('</script>', '<\\/script>')).replace('__TITLE__', '%s review, Grade %s' % (title, grade))
    out_dir = os.path.join(ROOT, 'dist', grade, uid)
    os.makedirs(out_dir, exist_ok=True)
    open(os.path.join(out_dir, 'index.html'), 'w').write(html)
    print('Built dist/%s/%s/index.html (%d bytes), %d IDs in registry' % (grade, uid, len(html), len(registry)))

if __name__ == '__main__':
    main()
